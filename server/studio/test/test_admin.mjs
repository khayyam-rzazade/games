// Logicers Studio: Khayyam's queue and actions, reports and the three-report hide. Run: node --test test/
import { test } from "node:test";
import assert from "node:assert/strict";
import { env, call, one, rows, maker, game, save, pick, setNow, resetBrakes } from "./lib.mjs";

const T0 = Date.UTC(2026, 10, 8, 9, 0, 0);

test("the admin key: a wrong one is 'nothing', ten of them and the address waits", async () => {
  setNow(T0);
  resetBrakes();
  const e = env();
  let r = await call(e, "POST", "/admin/queue", { key: "guess" }, { ip: "10.2.2.2" });
  assert.deepEqual([r.status, r.json.e], [404, "nothing"]);
  for (let i = 0; i < 9; i++) await call(e, "POST", "/admin/queue", { key: "guess" + i }, { ip: "10.2.2.2" });
  r = await call(e, "POST", "/admin/queue", { key: e.ADMIN_KEY }, { ip: "10.2.2.2" });
  assert.equal(r.status, 429, "even the right key waits after ten wrong ones");
  r = await call(e, "POST", "/admin/queue", { key: e.ADMIN_KEY });
  assert.equal(r.status, 200);
  r = await call(env({ ADMIN_KEY: undefined }), "POST", "/admin/queue", { key: "" });
  assert.equal(r.json.e, "nothing", "no ADMIN_KEY set: nothing opens");
});

test("the queue: every new thing with the maker's name, newest first; done; actions", async () => {
  setNow(T0);
  resetBrakes();
  const e = env();
  const a = await maker(e);
  const g = await game(e, a);
  await save(e, g, { items: [pick()], about: "See https://example.org/x" });
  let r = await call(e, "POST", "/admin/queue", { key: e.ADMIN_KEY });
  const kinds = r.json.queue.map((x) => x.kind);
  assert.deepEqual(kinds, ["link", "item", "about", "game", "maker"], "newest first");
  assert.equal(r.json.open, 5);
  const row = r.json.queue.find((x) => x.kind === "item");
  assert.equal(row.maker.name, "Anna Rossi");
  assert.equal(row.game.title, "History a day");
  assert.equal(row.game.want_listed, true);
  assert.equal(row.game.listed, false);
  assert.match(row.text, /Which came first\?/);
  assert.match(row.text, /\[Writing\]/, "the right choice is marked");
  r = await call(e, "POST", "/admin/act", { key: e.ADMIN_KEY, action: "done", id: row.id });
  assert.equal(r.json.ok, true);
  r = await call(e, "POST", "/admin/queue", { key: e.ADMIN_KEY });
  assert.equal(r.json.open, 4);
  assert.equal((await call(e, "POST", "/admin/queue", { key: e.ADMIN_KEY, all: true })).json.queue.length, 5);
  r = await call(e, "POST", "/admin/act", { key: e.ADMIN_KEY, game: g.id, action: "list" });
  assert.deepEqual(r.json.game, { id: g.id, status: "listed", listed: true, want_listed: true, hidden: null });
  r = await call(e, "POST", "/game/mine", { edit_key: g.edit_key });
  assert.equal(r.json.game.status, "listed");
  assert.ok(!JSON.stringify(r.json).match(/approved|checked/i), "the words approved and checked are never used");
  r = await call(e, "POST", "/admin/act", { key: e.ADMIN_KEY, game: g.id, action: "unlist" });
  assert.equal(r.json.game.status, "waiting", "the maker sees: Not listed yet");
  r = await call(e, "POST", "/admin/act", { key: e.ADMIN_KEY, game: g.id, action: "done" });
  r = await call(e, "POST", "/admin/queue", { key: e.ADMIN_KEY });
  assert.deepEqual(r.json.queue.map((x) => x.kind), ["maker"], "done for a game closes all its rows (the maker's own row stays)");
  assert.equal((await call(e, "POST", "/admin/act", { key: e.ADMIN_KEY, game: g.id, action: "approve" })).json.e, "action");
  assert.equal((await call(e, "POST", "/admin/act", { key: e.ADMIN_KEY, game: "x/y", action: "hide" })).status, 404);
  r = await call(e, "POST", "/admin/act", { key: e.ADMIN_KEY, game: g.code, action: "delete" });
  assert.equal(r.json.deleted, g.id, "a game may be named by its code too");
  assert.equal((await call(e, "GET", "/g/" + g.id + "/")).status, 404);
  r = await call(e, "POST", "/admin/queue", { key: e.ADMIN_KEY, all: true });
  assert.ok(r.json.queue.some((x) => x.kind === "act" && x.text === "delete"), "Khayyam's own acts are on record");
});

test("planted fault: three reports from three browsers hide the game until Khayyam looks", async () => {
  setNow(T0);
  resetBrakes();
  const e = env();
  const a = await maker(e);
  const g = await game(e, a);
  await save(e, g, { items: [pick()] });
  const rep = (browser, ip, reason) => call(e, "POST", "/report", { game: g.id, reason: reason || "hate", text: "This is not ok.", browser }, { ip });
  assert.equal((await rep("browser-0001", "10.3.0.1", "rude")).json.e, "reason");
  assert.equal((await rep("browser-0001", "10.3.0.1")).json.ok, true);
  assert.equal((await rep("browser-0001", "10.3.0.2")).json.ok, true, "the same browser again: thanked");
  assert.equal((await rep("browser-0002", "10.3.0.1")).json.ok, true, "the same address again: thanked");
  assert.equal((await one(e, "SELECT COUNT(*) AS n FROM reports")).n, 1, "and counted once");
  await rep("browser-0002", "10.3.0.3");
  assert.equal((await call(e, "GET", "/g/" + g.id + "/")).status, 200, "two reports: still up");
  await rep("browser-0003", "10.3.0.4");
  let r = await call(e, "GET", "/g/" + g.id + "/");
  assert.equal(r.status, 410, "three: hidden");
  r = await call(e, "POST", "/game/mine", { edit_key: g.edit_key });
  assert.equal(r.json.game.status, "hidden");
  assert.equal(r.json.game.hidden_by, "reports");
  r = await call(e, "POST", "/admin/queue", { key: e.ADMIN_KEY });
  assert.equal(r.json.reports.length, 1);
  assert.equal(r.json.reports[0].n, 3);
  assert.equal(r.json.reports[0].game.hidden, "reports");
  assert.ok(r.json.queue.some((x) => x.kind === "report" && /hidden by 3 reports/.test(x.text)));
  const stored = await rows(e, "SELECT * FROM reports");
  assert.ok(stored.every((x) => !x.browser_hash.includes("browser-")), "only a keyed hash of the browser's id");
  await call(e, "POST", "/admin/act", { key: e.ADMIN_KEY, game: g.id, action: "unhide" });
  assert.equal((await call(e, "GET", "/g/" + g.id + "/")).status, 200);
  assert.equal((await call(e, "POST", "/admin/queue", { key: e.ADMIN_KEY })).json.reports.length, 0, "unhide closes its reports");
  await rep("browser-0004", "10.3.0.5");
  assert.equal((await call(e, "GET", "/g/" + g.id + "/")).status, 200, "one new report after Khayyam looked does not hide it again");
  assert.equal((await call(e, "POST", "/report", { game: "nobody/nothing", reason: "spam" })).status, 404);
});
